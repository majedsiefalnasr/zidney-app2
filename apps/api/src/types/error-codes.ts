  [ErrorCode.USER_NOT_FOUND]: 404,
  [ErrorCode.LICENSE_NOT_FOUND]: 404,
  [ErrorCode.WORKSPACE_NOT_FOUND]: 404,

  // 409 Conflict
  [ErrorCode.CONFLICT]: 409,
  [ErrorCode.ATTEMPT_ALREADY_COMPLETED]: 409,
