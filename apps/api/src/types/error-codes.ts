/**
 * T058: Error Code Enum Definition
 *
 * Purpose: Define all error codes with HTTP status mappings
 * Constitutional Compliance: Standardized error responses
 */

export enum ErrorCode {
  // 4xx Client Errors
  BAD_REQUEST = 'BAD_REQUEST',
  VALIDATION_ERROR = 'VALIDATION_ERROR',
  MISSING_IDEMPOTENCY_KEY = 'MISSING_IDEMPOTENCY_KEY',
  MISSING_FIELD = 'MISSING_FIELD',
  INVALID_FORMAT = 'INVALID_FORMAT',
  PAYLOAD_TOO_LARGE = 'PAYLOAD_TOO_LARGE',

  // 401 Unauthorized
  UNAUTHORIZED = 'UNAUTHORIZED',
  INVALID_CREDENTIALS = 'INVALID_CREDENTIALS',
  TOKEN_EXPIRED = 'TOKEN_EXPIRED',
  INVALID_JWT = 'INVALID_JWT',

  // 403 Forbidden
  FORBIDDEN = 'FORBIDDEN',
  PERMISSION_DENIED = 'PERMISSION_DENIED',
  RBAC_VIOLATION = 'RBAC_VIOLATION',
  WORKSPACE_MISMATCH = 'WORKSPACE_MISMATCH',

  // 404 Not Found
  NOT_FOUND = 'NOT_FOUND',
  RESOURCE_NOT_FOUND = 'RESOURCE_NOT_FOUND',
  ATTEMPT_NOT_FOUND = 'ATTEMPT_NOT_FOUND',
  USER_NOT_FOUND = 'USER_NOT_FOUND',

  // 409 Conflict
  CONFLICT = 'CONFLICT',
  ATTEMPT_ALREADY_COMPLETED = 'ATTEMPT_ALREADY_COMPLETED',
  ATTEMPT_ALREADY_SUBMITTED = 'ATTEMPT_ALREADY_SUBMITTED',
  INVALID_STATE = 'INVALID_STATE',

  // 410 Gone
  GONE = 'GONE',
  ATTEMPT_EXPIRED = 'ATTEMPT_EXPIRED',

  // 423 Locked
  LOCKED = 'LOCKED',
  WORKSPACE_SOFT_LOCKED = 'WORKSPACE_SOFT_LOCKED',
  LICENSE_SOFT_LOCKED = 'LICENSE_SOFT_LOCKED',
  ACCOUNT_LOCKED = 'ACCOUNT_LOCKED',

  // 426 Upgrade Required
  UPGRADE_REQUIRED = 'UPGRADE_REQUIRED',
  SCHEMA_VERSION_INCOMPATIBLE = 'SCHEMA_VERSION_INCOMPATIBLE',

  // 429 Too Many Requests
  TOO_MANY_REQUESTS = 'TOO_MANY_REQUESTS',
  RATE_LIMIT_EXCEEDED = 'RATE_LIMIT_EXCEEDED',

  // 5xx Server Errors
  INTERNAL_ERROR = 'INTERNAL_SERVER_ERROR',
  DATABASE_ERROR = 'DATABASE_ERROR',
  REDIS_ERROR = 'REDIS_ERROR',
  SERVICE_UNAVAILABLE = 'SERVICE_UNAVAILABLE',
  WORKER_UNAVAILABLE = 'WORKER_UNAVAILABLE',
  GRADING_TIMEOUT = 'GRADING_TIMEOUT',

  // Service-specific
  LICENSE_NOT_FOUND = 'LICENSE_NOT_FOUND',
  WORKSPACE_ARCHIVED = 'WORKSPACE_ARCHIVED',
  WORKSPACE_DELETED = 'WORKSPACE_DELETED',
  WORKSPACE_NOT_FOUND = 'WORKSPACE_NOT_FOUND',
}

